import {readFile,writeFile} from 'node:fs/promises'
const root=new URL('./',import.meta.url)
const core=(await readFile(new URL('core.mjs',root),'utf8')).replace(/^export /gm,'')
const main=await readFile(new URL('main.js',root),'utf8')
await writeFile(new URL('code.js',root),'// Generated by build.mjs. Edit core.mjs and main.js instead.\n'+core+'\n'+main)
console.log('Built figma-importer/code.js')
